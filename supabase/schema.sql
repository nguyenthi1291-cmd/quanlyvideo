-- ==============================================================================
-- 1. EXTENSIONS & SCHEMAS
-- ==============================================================================
create extension if not exists "uuid-ossp";

-- ==============================================================================
-- 2. TABLES
-- ==============================================================================

-- 2.1 Profiles Table (Linked to Supabase auth.users)
create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  username text unique not null,
  email text,
  role text not null default 'USER' check (role in ('ADMIN', 'USER')),
  status text not null default 'ACTIVE' check (status in ('ACTIVE', 'INACTIVE')),
  avatar_url text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- 2.2 Video Categories Table
create table if not exists public.video_categories (
  id bigint generated by default as identity primary key,
  name text not null unique,
  slug text not null unique,
  description text,
  status text not null default 'ACTIVE' check (status in ('ACTIVE', 'INACTIVE')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- 2.3 Videos Table
create table if not exists public.videos (
  id bigint generated by default as identity primary key,
  title text not null,
  slug text unique,
  description text,
  category_id bigint references public.video_categories(id) on delete restrict,
  video_url text,
  video_path text,
  thumbnail_url text,
  thumbnail_path text,
  views bigint not null default 0 check (views >= 0),
  file_size bigint not null default 0 check (file_size >= 0),
  duration_seconds integer default 0 check (duration_seconds >= 0),
  status text not null default 'ACTIVE' check (status in ('ACTIVE', 'INACTIVE', 'DRAFT')),
  created_by uuid references public.profiles(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- 2.4 Video Views Log Table (One row per view event for analytics)
create table if not exists public.video_views (
  id bigint generated by default as identity primary key,
  video_id bigint not null references public.videos(id) on delete cascade,
  viewer_id uuid references auth.users(id) on delete set null,
  ip_hash text,
  user_agent text,
  viewed_at timestamptz not null default now()
);

-- ==============================================================================
-- 3. INDEXES
-- ==============================================================================
create index if not exists idx_profiles_username on public.profiles(username);
create index if not exists idx_profiles_role on public.profiles(role);
create index if not exists idx_profiles_status on public.profiles(status);

create index if not exists idx_video_categories_slug on public.video_categories(slug);
create index if not exists idx_video_categories_status on public.video_categories(status);

create index if not exists idx_videos_category on public.videos(category_id);
create index if not exists idx_videos_status on public.videos(status);
create index if not exists idx_videos_views on public.videos(views desc);
create index if not exists idx_videos_created_at on public.videos(created_at desc);
create index if not exists idx_videos_slug on public.videos(slug);

create index if not exists idx_video_views_video_id on public.video_views(video_id);
create index if not exists idx_video_views_viewed_at on public.video_views(viewed_at);

drop policy if exists "Users can update their own profile info" on public.profiles;
drop policy if exists "Admin full update access to profiles" on public.profiles;
drop policy if exists "Admin delete access to profiles" on public.profiles;

create policy "Users can read their own profile or Admin can read all"
on public.profiles for select
to authenticated
using (auth.uid() = id or public.is_admin());

create policy "Users can update their own profile info"
on public.profiles for update
to authenticated
using (auth.uid() = id)
with check (auth.uid() = id and (role = 'USER' or public.is_admin()));

create policy "Admin full update access to profiles"
on public.profiles for update
to authenticated
using (public.is_admin())
with check (public.is_admin());

create policy "Admin delete access to profiles"
on public.profiles for delete
to authenticated
using (public.is_admin());

